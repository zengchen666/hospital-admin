-- =============================================================================
-- 权限补丁：患者 / 挂号模块的查询权限
--
-- 背景：08_seed.sql 初始化时只给了增删改类权限码，漏了查询码，
-- 导致 patient/page、registration/schedule 这类接口无权限可用（40301）。
-- 本脚本幂等，可重复执行。
-- =============================================================================

USE `hospital`;

-- ---------------------------------------------------------------------------
-- 1. 补权限点（id 3054、3055 为新增段，不与其他权限冲突）
-- ---------------------------------------------------------------------------
INSERT INTO `sys_permission`
    (`id`, `perm_code`, `perm_name`, `perm_type`, `menu_id`, `data_scope`, `status`)
VALUES
    (3054, 'patient:query',      '患者查询', 2, NULL, 1, 1),
    (3055, 'registration:query', '挂号查询', 2, NULL, 1, 1)
ON DUPLICATE KEY UPDATE
    `perm_name` = VALUES(`perm_name`),
    `status`    = VALUES(`status`);

-- ---------------------------------------------------------------------------
-- 2. 授予超级管理员（角色 2001）
--    其他角色待角色管理模块上线后按岗位配置
-- ---------------------------------------------------------------------------
INSERT INTO `sys_role_permission` (`id`, `role_id`, `permission_id`)
VALUES
    (9054, 2001, 3054),
    (9055, 2001, 3055)
ON DUPLICATE KEY UPDATE
    `deleted` = 0;
